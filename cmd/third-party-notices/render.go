package main

import (
	"fmt"
	"strings"
)

// entry is one redistributed component and the license files that travel with it.
type entry struct {
	name    string
	version string
	note    string

	// declared is the license expression the package's manifest declares (npm packages); empty when there is none.
	declared string

	// license summarizes the licenses of the component, set by checkEntry: declared when there is one, otherwise
	// what the license files were classified as.
	license string

	files []licenseFile
}

// licenseFile is a license or notice file as its component ships it.
type licenseFile struct {
	name string // file name upstream, e.g. LICENSE.txt
	path string // identifies the file across versions, e.g. "golang.org/x/sys/LICENSE"; keys the overrides
	text string // normalized with normalize

	// notice marks attribution notices (Apache-2.0's NOTICE files): printed, never classified.
	notice bool

	license string // what the file was classified as, set by checkEntry
}

// section is a titled group of entries in the notices file.
type section struct {
	title   string
	intro   string
	entries []entry
}

// header opens the notices file.
const header = `Third-party software notices for BaguetteDB

This file lists the third-party software redistributed with BaguetteDB,
in the bdb binaries and in the web app they serve, with the license texts
and notices that must accompany it.

It is generated by cmd/third-party-notices from what the build ships: the
Go modules linked into bdb on every release platform, the Go standard
library, the packages bundled into the web app and its service worker, and
the native libraries the release build links. Do not edit it by hand: run
make notices after any dependency change.

A license text shared word for word by several components is printed
once, under "Shared license texts" at the end, and referenced by number.
`

const (
	sectionRule = "=========================================================================="
	entryRule   = "--------------------------------------------------------------------------"
	textIndent  = "    "
)

// render writes the notices file: the header, then each section's entries with their license files, then the
// license texts several files share word for word, each printed once.
func render(sections []section) string {
	shared := sharedTexts(sections)

	var b strings.Builder
	b.WriteString(header)
	for _, s := range sections {
		fmt.Fprintf(&b, "\n%s\n%s\n%s\n\n%s\n", sectionRule, s.title, sectionRule, wrap(s.intro, len(sectionRule)))
		for _, e := range s.entries {
			renderEntry(&b, e, shared)
		}
	}

	if len(shared.texts) > 0 {
		fmt.Fprintf(&b, "\n%s\nShared license texts\n%s\n", sectionRule, sectionRule)
		for i, t := range shared.texts {
			fmt.Fprintf(&b, "\n%s\n[%d] %s\n%s\n\n", entryRule, i+1, t.license, entryRule)
			fmt.Fprintf(&b, "%s\n\n", wrap("Used by: "+strings.Join(t.usedBy, ", ")+".", len(sectionRule)))
			writeIndented(&b, t.text)
		}
	}
	return strings.TrimRight(b.String(), "\n") + "\n"
}

// renderEntry writes one entry: its title, note and license, then each license file, inline or as a reference to
// a shared text.
func renderEntry(b *strings.Builder, e entry, shared sharedSet) {
	title := e.name
	if e.version != "" {
		title += " " + e.version
	}
	fmt.Fprintf(b, "\n%s\n%s\n%s\n\n", entryRule, title, entryRule)
	if e.note != "" {
		fmt.Fprintf(b, "%s\n\n", wrap(e.note, len(entryRule)))
	}
	if e.license != "" {
		fmt.Fprintf(b, "License: %s\n\n", e.license)
	}
	for _, f := range e.files {
		if n, ok := shared.index[key(f.text)]; ok {
			fmt.Fprintf(b, "%s: shared text [%d] below.\n\n", f.name, n)
			continue
		}
		fmt.Fprintf(b, "%s:\n\n", f.name)
		writeIndented(b, f.text)
	}
}

// sharedText is a license text several files carry word for word.
type sharedText struct {
	license string
	text    string
	usedBy  []string
}

// sharedSet holds the shared texts in order of first use, and their 1-based numbers by key.
type sharedSet struct {
	texts []sharedText
	index map[string]int
}

// sharedTexts finds the texts that more than one file carries, compared on their words so that line wrapping and
// indentation do not matter. Each is numbered in order of first use and printed with the first copy's layout.
func sharedTexts(sections []section) sharedSet {
	counts := map[string]int{}
	for _, s := range sections {
		for _, e := range s.entries {
			for _, f := range e.files {
				counts[key(f.text)]++
			}
		}
	}

	set := sharedSet{index: map[string]int{}}
	for _, s := range sections {
		for _, e := range s.entries {
			for _, f := range e.files {
				k := key(f.text)
				if counts[k] < 2 {
					continue
				}
				n, ok := set.index[k]
				if !ok {
					license := f.license
					if f.notice {
						license = "Notice"
					}
					set.texts = append(set.texts, sharedText{license: license, text: f.text})
					n = len(set.texts)
					set.index[k] = n
				}
				set.texts[n-1].usedBy = appendUnique(set.texts[n-1].usedBy, e.name)
			}
		}
	}
	return set
}

// key identifies a text by its words, ignoring layout.
func key(text string) string {
	return strings.Join(strings.Fields(text), " ")
}

// normalize makes a license text's layout platform-independent: LF line endings, no trailing whitespace on any line,
// no blank lines before or after the text.
func normalize(text string) string {
	text = strings.ReplaceAll(text, "\r\n", "\n")
	text = strings.ReplaceAll(text, "\r", "\n")
	lines := strings.Split(text, "\n")
	for i, l := range lines {
		lines[i] = strings.TrimRight(l, " \t")
	}
	return strings.Trim(strings.Join(lines, "\n"), "\n")
}

// writeIndented writes text with every non-empty line indented, followed by a blank line.
func writeIndented(b *strings.Builder, text string) {
	for line := range strings.SplitSeq(text, "\n") {
		if line != "" {
			b.WriteString(textIndent)
			b.WriteString(line)
		}
		b.WriteString("\n")
	}
	b.WriteString("\n")
}

// wrap breaks text into lines of at most width characters, at spaces.
func wrap(text string, width int) string {
	var lines []string
	line := ""
	for word := range strings.FieldsSeq(text) {
		if line != "" && len(line)+1+len(word) > width {
			lines = append(lines, line)
			line = word
			continue
		}
		if line != "" {
			line += " "
		}
		line += word
	}
	return strings.Join(append(lines, line), "\n")
}
