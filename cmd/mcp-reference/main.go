// Command mcp-reference renders the reference documentation under docs/reference from the code: the MCP tool
// registrations of every module, the embedded manuals served by get_docs, and the gateway's agent instructions.
// The output is committed and checked by CI, so the reference cannot drift from the tools an instance exposes.
package main

import (
	"errors"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	mcplib "github.com/mark3labs/mcp-go/mcp"
	"github.com/rs/zerolog"

	bdbsmcp "github.com/alexandremgo/baguettedb/pkg/bdbs/mcp"
	"github.com/alexandremgo/baguettedb/pkg/common/config"
	"github.com/alexandremgo/baguettedb/pkg/common/mcputil"
	"github.com/alexandremgo/baguettedb/pkg/common/quota"
	databasesmcp "github.com/alexandremgo/baguettedb/pkg/databases/mcp"
	"github.com/alexandremgo/baguettedb/pkg/mcpgateway"
	startersmcp "github.com/alexandremgo/baguettedb/pkg/starters/mcp"
)

// generatedHeader opens every rendered file, so a reader editing it by hand is told where the source is.
const generatedHeader = "<!-- Generated by cmd/mcp-reference. Do not edit; run make docs-reference. -->\n\n"

func main() {
	out := flag.String("out", "docs/reference", "directory the reference files are written to")
	flag.Parse()

	if err := run(*out); err != nil {
		fmt.Fprintln(os.Stderr, "mcp-reference:", err)
		os.Exit(1)
	}
}

// run renders every reference file into dir, creating it when missing. A rendering error leaves the files that
// were already written in place; the caller's `git diff` shows the partial result.
func run(dir string) error {
	files, err := renderAll(collectTools())
	if err != nil {
		return err
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return fmt.Errorf("creating %s: %w", dir, err)
	}
	for name, content := range files {
		path := filepath.Join(dir, name)
		if err := os.WriteFile(path, []byte(generatedHeader+content), 0o644); err != nil {
			return fmt.Errorf("writing %s: %w", path, err)
		}
	}
	return nil
}

// collectTools lists the tools of every module MCP server, with the starters tools registered on the bdbs server
// as on a running instance. Registration only captures the services in closures, never calls them, so the servers
// are built without any and the listing carries the exact names, descriptions and input schemas an instance
// exposes.
func collectTools() []mcplib.Tool {
	logger := zerolog.Nop()
	bdbsServer := bdbsmcp.NewServer(nil, nil, bdbsmcp.Options{}, logger)
	startersmcp.RegisterTools(bdbsServer, nil, logger)
	databasesServer := databasesmcp.NewServer(nil, nil, nil, logger)

	var tools []mcplib.Tool
	for _, listed := range bdbsServer.ListTools() {
		tools = append(tools, listed.Tool)
	}
	for _, listed := range databasesServer.ListTools() {
		tools = append(tools, listed.Tool)
	}
	return tools
}

// defaultLimits are the per-request SQL caps an instance enforces when its configuration leaves them unset, the
// values the SQL reference quotes.
var defaultLimits = quota.Limits{
	MaxStatementsPerRequest: config.DefaultQuotaMaxStatementsPerRequest,
	MaxRowsPerRequest:       config.DefaultQuotaMaxRowsPerRequest,
	MaxQueryResultRows:      config.DefaultQuotaMaxQueryResultRows,
	MaxConcurrentQueries:    config.DefaultQuotaMaxConcurrentQueries,
}

// renderAll renders every reference file, keyed by file name. The manuals render with defaultLimits.
func renderAll(tools []mcplib.Tool) (map[string]string, error) {
	files := map[string]string{}

	toolsDoc, err := renderToolsDoc(tools)
	if err != nil {
		return nil, err
	}
	files["mcp-tools.md"] = toolsDoc

	for _, topic := range databasesmcp.DocTopics() {
		doc, err := databasesmcp.RenderDocs(topic, defaultLimits)
		if err != nil {
			return nil, fmt.Errorf("rendering %s manual: %w", topic, err)
		}
		if note, ok := manualNotes[topic]; ok {
			if doc, err = addNoteUnderTitle(doc, note); err != nil {
				return nil, fmt.Errorf("annotating %s manual: %w", topic, err)
			}
		}
		files[topic+".md"] = doc
	}

	files["agent-instructions.md"] = renderInstructionsDoc()
	return files, nil
}

// manualNotes holds, per manual, a note the reference adds under the title. A manual addresses the agent reading
// it from its own instance; a note frames what only holds there once the text is read as documentation.
var manualNotes = map[string]string{
	"sql": "The limits in [Statement limits](#statement-limits) are an instance's defaults: an instance can " +
		"configure its own, and `" + mcputil.ToolGetDocs + "` gives an agent the values of the instance it is " +
		"connected to.",
}

// addNoteUnderTitle inserts note as a blockquote paragraph right after the document's H1, which must be its
// first line.
func addNoteUnderTitle(doc, note string) (string, error) {
	title, rest, found := strings.Cut(doc, "\n")
	if !found || !strings.HasPrefix(title, "# ") {
		return "", errors.New("document does not open with an H1")
	}
	return title + "\n\n> " + note + "\n\n" + strings.TrimLeft(rest, "\n"), nil
}

// renderInstructionsDoc wraps the gateway instructions with a preamble saying what they are.
func renderInstructionsDoc() string {
	return "# Agent instructions\n\n" +
		"Every MCP session receives this text from the server before its first tool call. It is the orientation " +
		"agents work from; the descriptions in the [tool reference](mcp-tools.md) complete it.\n\n" +
		"---\n\n" + mcpgateway.Instructions + "\n"
}
